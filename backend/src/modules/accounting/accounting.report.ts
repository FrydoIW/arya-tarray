import ExcelJS from "exceljs";
import { getAccountingReport } from "./accounting.service.js";
import type { AccountingQuery } from "./accounting.schema.js";
import { buildAccountingPdf } from "./accounting.pdf.js";

/** Both export formats consume exactly the report read model. Decimal amounts stay text in Excel. */
export async function exportAccountingReport(q: AccountingQuery, actor: string) {
  const report = await getAccountingReport(q, true);
  const name = `accounting-${q.view}-${q.from}`;
  if (q.format === "xlsx") {
    const workbook = new ExcelJS.Workbook();
    const metadata = workbook.addWorksheet("Coverage and totals");
    metadata.addRows([["Report", q.view], ["Cutover", report.cutoverDate], ["Coverage", report.coverage],
      ["Total debit", report.totalDebit], ["Total credit", report.totalCredit], ["Period movement balance", report.movementBalance],
      ["Generated by", actor], ["Preview", report.preview ? "PREVIEW - NOT POSTED" : "Posted journal scope"],
      ["Filters", JSON.stringify(q)]]);
    metadata.getColumn(1).width = 25; metadata.getColumn(2).width = 70;
    const sheet = workbook.addWorksheet("Report");
    const keys = [...new Set(report.rows.flatMap(row => Object.keys(row)))];
    sheet.columns = keys.map(key => ({ header: key, key, width: key.includes("journal") || key.endsWith("Id") ? 45 : 25 }));
    report.rows.forEach(row => sheet.addRow(row));
    sheet.getRow(1).font = { bold: true }; sheet.views = [{ state: "frozen", ySplit: 1 }];
    if (report.additions.length) workbook.addWorksheet("Manual preview - first 100").addRows([
      ["Date", "Amount", "Description", "State"], ...report.additions.map(a => [a.date, a.amount, a.description, a.state])
    ]);
    return { buffer: Buffer.from(await workbook.xlsx.writeBuffer()), fileName: `${name}.xlsx`,
      contentType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" };
  }
  const buffer = buildAccountingPdf(report, actor);
  return { buffer, fileName: `${name}.pdf`, contentType: "application/pdf" };
}

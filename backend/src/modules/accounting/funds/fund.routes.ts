import { Router } from "express";
import { asyncHandler } from "../../../lib/http.js";
import { requireMenuAccess } from "../../../middleware/authorization.js";
import { ACCOUNTING_MANAGE, ACCOUNTING_POST } from "../approval/approval.repository.js";
import { fundController as c } from "./fund.controller.js";
export const fundRouter = Router();
const manage = requireMenuAccess(ACCOUNTING_MANAGE), post = requireMenuAccess(ACCOUNTING_POST);
fundRouter.get("/fund-contribution-sources", asyncHandler(c.sources));
fundRouter.get("/funds", asyncHandler(c.list));
fundRouter.post("/funds", manage, asyncHandler(c.create));
fundRouter.get("/funds/:id", asyncHandler(c.detail("FUND")));
fundRouter.patch("/funds/:id", manage, asyncHandler(c.revise));
fundRouter.post("/funds/:id/submit", manage, asyncHandler(c.submit("FUND_SETUP")));
fundRouter.post("/funds/:id/apply", post, asyncHandler(c.apply));
fundRouter.post("/funds/:id/commands", manage, asyncHandler(c.command));
fundRouter.get("/funds/:id/restrictions", asyncHandler(c.children("RESTRICTION")));
fundRouter.post("/funds/:id/restrictions", manage, asyncHandler(c.restriction));
fundRouter.get("/funds/:id/designations", asyncHandler(c.children("DESIGNATION")));
fundRouter.post("/funds/:id/designations", manage, asyncHandler(c.designation));
fundRouter.get("/funds/:id/movements", asyncHandler(c.children("MOVEMENT")));
fundRouter.post("/funds/:id/movements", manage, asyncHandler(c.movement));
fundRouter.get("/funds/:id/releases", asyncHandler(c.children("RELEASE")));
fundRouter.get("/funds/:id/journals", asyncHandler(c.children("JOURNAL")));
fundRouter.get("/funds/:id/balances", asyncHandler(c.balances));
fundRouter.get("/funds/:id/utilization", asyncHandler(c.balances));
fundRouter.get("/funds/:id/reconciliation", asyncHandler(c.reconciliation));
fundRouter.get("/fund-restrictions/:id", asyncHandler(c.detail("RESTRICTION")));
fundRouter.patch("/fund-restrictions/:id", manage, asyncHandler(c.reviseRestriction));
fundRouter.post("/fund-restrictions/:id/submit", manage, asyncHandler(c.submit("FUND_RESTRICTION")));
fundRouter.post("/fund-restrictions/:id/releases", manage, asyncHandler(c.release));
fundRouter.post("/fund-restrictions/:id/apply", post, asyncHandler(c.apply));
fundRouter.post("/fund-restrictions/:id/cancel", manage, asyncHandler(c.cancel("RESTRICTION")));
fundRouter.get("/fund-designations/:id", asyncHandler(c.detail("DESIGNATION")));
fundRouter.post("/fund-designations/:id/submit", manage, asyncHandler(c.submit("FUND_DESIGNATION")));
fundRouter.post("/fund-designations/:id/apply", post, asyncHandler(c.apply));
fundRouter.post("/fund-designations/:id/cancel", manage, asyncHandler(c.cancel("DESIGNATION")));
fundRouter.get("/fund-movements/:id", asyncHandler(c.detail("MOVEMENT")));
fundRouter.post("/fund-movements/:id/submit", manage, asyncHandler(c.submitMovement));
fundRouter.post("/fund-movements/:id/apply", post, asyncHandler(c.apply));
fundRouter.post("/fund-movements/:id/cancel", manage, asyncHandler(c.cancel("MOVEMENT")));

import { PdfDocument } from "../reconciliation/transaction-inquiry/transaction-inquiry.pdf.js";
import type { getAccountingReport } from "./accounting.service.js";

export function buildAccountingPdf(report: Awaited<ReturnType<typeof getAccountingReport>>, actor: string) {
  const doc = new PdfDocument();
  let page = doc.addPage();
  let top = 125;
  const heading = () => {
    page.text(36, 35, `Accounting - ${report.view}`, 16, true);
    page.text(36, 55, `${report.filters.from} to ${report.filters.to ?? "onward"}; cutover ${report.cutoverDate}`, 9);
    page.text(36, 70, report.preview ? "PREVIEW - NOT POSTED" : report.coverage, 9);
    page.text(36, 85, `Debit ${report.totalDebit}   Credit ${report.totalCredit}   Period movement ${report.movementBalance}`, 9, true);
    page.text(36, 100, `Generated by ${actor}. ${report.trialScope}`, 8);
    page.line(36, 110, 806, 110);
  };
  heading();
  for (const row of [...report.rows, ...report.additions]) {
    const fields = Object.entries(row).filter(([key, value]) => value != null && !["id", "journalId", "relatedJournal"].includes(key));
    const height = fields.length * 12 + 12;
    if (top + height > 550) { page = doc.addPage(); heading(); top = 125; }
    for (const [key, value] of fields) {
      // Exact monetary strings fit intact; long narrative evidence is available through journal detail.
      page.text(36, top, `${key}: ${String(value).slice(0, 135)}`, 8); top += 12;
    }
    page.line(36, top + 2, 806, top + 2); top += 12;
  }
  doc.pages.forEach((p, i) => p.text(36, 575, `Phase 1 accounting evidence / Page ${i + 1} of ${doc.pages.length}`, 8));
  return doc.build();
}

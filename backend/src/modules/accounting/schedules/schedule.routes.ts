import { Router } from "express";
import { asyncHandler } from "../../../lib/http.js";
import { requireMenuAccess } from "../../../middleware/authorization.js";
import { ACCOUNTING_MANAGE, ACCOUNTING_POST } from "../approval/approval.repository.js";
import { stage23Controller as c } from "./schedule.controller.js";
export const scheduleRouter = Router();
const manage = requireMenuAccess(ACCOUNTING_MANAGE), post = requireMenuAccess(ACCOUNTING_POST);
scheduleRouter.get("/accruals/scheduled-reversals", asyncHandler(c.dueReversals));
scheduleRouter.get("/accruals", asyncHandler(c.listAccruals));
scheduleRouter.post("/accruals", manage, asyncHandler(c.createAccrual));
scheduleRouter.get("/accruals/:id", asyncHandler(c.getAccrual));
scheduleRouter.patch("/accruals/:id", manage, asyncHandler(c.updateAccrual));
scheduleRouter.post("/accruals/:id/cancel", manage, asyncHandler(c.cancelAccrual));
scheduleRouter.post("/accruals/:id/adjustments", manage, asyncHandler(c.adjustAccrual));
scheduleRouter.post("/accruals/:id/submit", manage, asyncHandler(c.submitAccrual));
scheduleRouter.post("/accruals/:id/post", post, asyncHandler(c.apply));
scheduleRouter.post("/accruals/:id/reversal-requests", manage, asyncHandler(c.reverseAccrual));
scheduleRouter.post("/accruals/:id/scheduled-reversal", manage, asyncHandler(c.scheduledReversal));
scheduleRouter.post("/schedules/preview", manage, asyncHandler(c.preview));
scheduleRouter.get("/schedules", asyncHandler(c.listSchedules));
scheduleRouter.post("/schedules", manage, asyncHandler(c.createSchedule));
scheduleRouter.get("/schedules/:id", asyncHandler(c.getSchedule));
scheduleRouter.get("/schedules/:id/periods", asyncHandler(c.periodList));
scheduleRouter.post("/schedules/:id/requests", manage, asyncHandler(c.command));
scheduleRouter.post("/schedules/:id/apply", post, asyncHandler(c.apply));
scheduleRouter.get("/schedule-periods/:id", asyncHandler(c.period));
scheduleRouter.post("/schedule-periods/:id/submit", manage, asyncHandler(c.submitPeriod));
scheduleRouter.post("/schedule-periods/:id/post", post, asyncHandler(c.apply));

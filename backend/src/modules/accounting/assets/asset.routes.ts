import { Router } from "express";
import { asyncHandler } from "../../../lib/http.js";
import { requireMenuAccess } from "../../../middleware/authorization.js";
import { ACCOUNTING_MANAGE, ACCOUNTING_POST } from "../approval/approval.repository.js";
import { assetController as c } from "./asset.controller.js";
export const assetRouter = Router();
const manage = requireMenuAccess(ACCOUNTING_MANAGE), post = requireMenuAccess(ACCOUNTING_POST);
assetRouter.get("/asset-categories", asyncHandler(c.list("CATEGORY")));
assetRouter.post("/asset-categories", manage, asyncHandler(c.createCategory));
assetRouter.get("/asset-categories/:id", asyncHandler(c.category));
assetRouter.patch("/asset-categories/:id", manage, asyncHandler(c.updateCategory));
assetRouter.get("/assets/reconciliation", asyncHandler(c.reconciliation));
assetRouter.get("/assets", asyncHandler(c.list("ASSET")));
assetRouter.post("/assets", manage, asyncHandler(c.createAsset));
assetRouter.get("/assets/:id", asyncHandler(c.asset));
assetRouter.patch("/assets/:id", manage, asyncHandler(c.updateAsset));
assetRouter.get("/assets/:id/journals", asyncHandler(c.journals));
assetRouter.post("/assets/:id/changes", manage, asyncHandler(c.change));
assetRouter.post("/assets/:id/submit", manage, asyncHandler(c.submit("ASSET")));
assetRouter.post("/assets/:id/activate", post, asyncHandler(c.post));
assetRouter.post("/assets/:id/cancel", manage, asyncHandler(c.cancel("ASSET")));
assetRouter.get("/asset-changes/:id", asyncHandler(c.changeDetail));
assetRouter.post("/asset-changes/:id/refresh", manage, asyncHandler(c.refreshChange));
assetRouter.post("/asset-changes/:id/submit", manage, asyncHandler(c.submit("CHANGE")));
assetRouter.post("/asset-changes/:id/post", post, asyncHandler(c.post));
assetRouter.post("/asset-changes/:id/cancel", manage, asyncHandler(c.cancel("CHANGE")));
assetRouter.post("/depreciation-runs/preview", manage, asyncHandler(c.preview));
assetRouter.get("/depreciation-runs", asyncHandler(c.list("RUN")));
assetRouter.post("/depreciation-runs", manage, asyncHandler(c.createRun));
assetRouter.get("/depreciation-runs/:id", asyncHandler(c.run));
assetRouter.post("/depreciation-runs/:id/refresh", manage, asyncHandler(c.refreshRun));
assetRouter.post("/depreciation-runs/:id/submit", manage, asyncHandler(c.submit("RUN")));
assetRouter.post("/depreciation-runs/:id/post", post, asyncHandler(c.post));
assetRouter.post("/depreciation-runs/:id/cancel", manage, asyncHandler(c.cancel("RUN")));
